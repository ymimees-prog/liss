def render_lesson(subject: str, title: str) -> str:
    """HTML text of a mini-lesson for a topic (built-in or a generic study plan)."""
    lesson = LESSONS.get(title)
    head = f"<i>{escape(subject)}</i>\n<b>📖 {escape(title)}</b>\n\n"
    if lesson is None:
        return head + (
            "Своего урока по этой теме у меня нет, но вот план на 30–40 минут:\n"
            "1. Найди 1 видео или статью по теме (ссылки ниже) и посмотри без отвлечений.\n"
            "2. Запиши конспект своими словами — 5–7 пунктов.\n"
            "3. Закрой конспект и объясни тему вслух, как будто учишь подругу.\n"
            "4. Реши 2–3 задачи или ответь на вопросы из учебника.\n\n" + search_links(subject, title)
        )
    parts = [head + escape(lesson.explain)]
    if lesson.code:
        parts.append(f"<pre>{escape(lesson.code)}</pre>")
    parts.append(f"✍️ <b>Задание:</b> {escape(lesson.task)}")
    if lesson.check:
        parts.append("❓ <b>Проверь себя:</b>\n" + "\n".join(f"• {escape(q)}" for q in lesson.check))
    parts.append(search_links(subject, title))
    return "\n\n".join(parts)


def review_questions(title: str) -> str:
    lesson = LESSONS.get(title)
    if not lesson or not lesson.check:
        return "Объясни тему вслух за 1 минуту, без подсказок."
    return "Ответь без подсказок:\n" + "\n".join(f"• {escape(q)}" for q in lesson.check)
